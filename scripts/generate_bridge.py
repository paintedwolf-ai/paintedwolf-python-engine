#define PW_PY_CPYTHON_WASM_SHA256 "5ce0cbeb843e6e5abf2d50c7158002e8333c26a40fbe27a7a52e66ee48cf64a8"
#endif
#ifndef PW_PY_METERED_WASM_SHA256
#define PW_PY_METERED_WASM_SHA256 "774a08a7863c1dee1b2f21bb80fb9964f0dd5dc27bdf2294bdd8a11934e893c6"
#endif
