#define PW_PY_ENGINE_TAG "pw-cpython-wasi-engine-v0.1.0"
#endif
#ifndef PW_PY_SOURCE_COMMIT
#define PW_PY_SOURCE_COMMIT "unknown"
#endif
#ifndef PW_PY_PLATFORM
#define PW_PY_PLATFORM "unknown"
#endif
